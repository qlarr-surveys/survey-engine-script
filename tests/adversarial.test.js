const validateInstruction = (script, allowedVariables = ["Q1.value"]) => {
  const instructionList = [
    {
      script: script,
      allowedVariables: allowedVariables,
    },
  ];
  const result = isSafeCode(JSON.stringify(instructionList));
  return JSON.parse(result)[0];
};

